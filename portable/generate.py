"""Generate dependency-free C and Java rules from the public product catalog."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent


def contract_outputs(data):
    """Generate additive vocabulary and strict typed field predicates, no adapters."""
    constants = dict(data['portableContract']['constants'])
    # Display policy keeps its existing catalog owner.
    constants['CAP_DISPLAY_POLICY'] = data['displayPolicy']['capability']
    constants['CAP_DISPLAY_POLICY_VERSION'] = data['displayPolicy']['version']
    assert data['portableContract']['version'] == data['inputVocabulary']['version'] == 1
    assert not (constants.keys() & data['inputVocabulary']['constants'].keys())
    constants.update(data['inputVocabulary']['constants'])
    assert all(type(v) in (int, str) for v in constants.values())
    assert all(re.fullmatch(r'[A-Z][A-Z_0-9]*', key) for key in constants)
    assert all(type(v) is str or 0 <= v <= 2147483647 for v in constants.values())
    assert all(0 <= a <= b <= 255 for a, b in data['inputVocabulary']['virtualKeyRanges'])
    assert all(0 <= v <= 255 for v in data['inputVocabulary']['virtualKeySingles'])
    predicates = [
        ('boolean_valid', ['value'], 'value == 0 || value == 1'),
        ('version_supported', ['value'], 'value == 1'),
        ('sequence_valid', ['value'], 'value > 0 && value <= SEQUENCE_MAX'),
        ('rate_valid', ['value'], 'value >= RATE_MIN_KBPS && value <= RATE_MAX_KBPS'),
        ('workspace_valid', ['width', 'height', 'scale'],
         'width >= WIDTH_MIN && width <= WIDTH_MAX && height >= HEIGHT_MIN && height <= HEIGHT_MAX && '
         'width % SIZE_ALIGNMENT == 0 && height % SIZE_ALIGNMENT == 0 && (scale == SCALE_MIN || scale == SCALE_MAX)'),
        ('hid_key_valid', ['value'], ' || '.join('value == ' + str(v) for v in sorted(set(
            v for k, v in data['inputVocabulary']['constants'].items() if k.startswith('HID_KEY_'))))),
        ('virtual_key_valid', ['value'], ' || '.join(
            [f'(value >= {a} && value <= {b})' for a, b in data['inputVocabulary']['virtualKeyRanges']] +
            [f'value == {v}' for v in data['inputVocabulary']['virtualKeySingles']])),
        ('modifiers_valid', ['value'], 'value >= 0 && value <= 255'),
        ('button_valid', ['value'], 'value >= BUTTON_PRIMARY && value <= BUTTON_FORWARD'),
        ('input_kind_valid', ['value'], 'value >= INPUT_KEY_DOWN && value <= INPUT_SCROLL'),
    ]
    c = '''// SPDX-License-Identifier: MIT
// Generated by portable/generate.py. Edit portable/catalog.json instead.
#ifndef DESKPORT_PORTABLE_CONTRACTS_H
#define DESKPORT_PORTABLE_CONTRACTS_H
#include <stdint.h>
'''
    java = '''// SPDX-License-Identifier: MIT
// Generated by portable/generate.py. Edit portable/catalog.json instead.
package com.deskport.core;

public final class DPContracts {
    private DPContracts() {}
'''
    for name, value in constants.items():
        literal = json.dumps(value)
        c += f'#define DP_{name} {literal}\n'
        java += f'    public static final {"String" if isinstance(value, str) else "int"} {name} = {literal};\n'
    for name, params, expression in predicates:
        c_expression = re.sub(r'\b[A-Z][A-Z_0-9]*\b', lambda m: 'DP_' + m[0], expression)
        c += f'static inline int dp_contract_{name}(' + ', '.join('int64_t ' + p for p in params) + f') {{\n    return {c_expression};\n}}\n'
        java_name = name.split('_')[0] + ''.join(p.title() for p in name.split('_')[1:])
        java += f'    public static boolean {java_name}(' + ', '.join('long ' + p for p in params) + f') {{\n        return {expression};\n    }}\n'
    return {ROOT / 'include/deskport/contracts.h': c + '#endif\n',
            ROOT / 'java/com/deskport/core/DPContracts.java': java + '}\n'}


def outputs():
    data = json.loads((ROOT / 'catalog.json').read_text())
    if data['schemaVersion'] != 1 or data['license'] != 'MIT':
        raise ValueError('Unsupported catalog schema or license')
    net, tuning, policy = (data[k] for k in ('network', 'desktopTuning', 'displayPolicy'))
    assert all(type(v) is int for v in net.values())
    assert net['basePort'] > 0 and net['portStep'] > 0 and net['portCount'] > 0
    assert 0 < net['controlOffset'] < net['portStep']
    assert net['basePort'] + (net['portCount'] - 1) * net['portStep'] + net['controlOffset'] <= 65535
    assert tuning['values'] == sorted(set(tuning['values'])) and tuning['default'] in tuning['values']
    assert all(0 < x <= 10 for x in tuning['values'])
    assert len(set(policy['values'].values())) == len(policy['values'])
    numbers = ', '.join(f'{v:.1f}' for v in tuning['values'])
    labels = ', '.join(json.dumps(f'{v:.1f}') for v in tuning['values'])
    constants = {'BASE_PORT': net['basePort'], 'PORT_STEP': net['portStep'], 'PORT_COUNT': net['portCount'],
                 'CONTROL_OFFSET': net['controlOffset'], 'BINDING_PORT': net['bindingPort'], 'TUNING_COUNT': len(tuning['values']),
                 'TUNING_DEFAULT_INDEX': tuning['values'].index(tuning['default']),
                 'DISPLAY_POLICY_VERSION': policy['version']}
    constants.update({'POLICY_' + k: v for k, v in policy['values'].items()})
    constants['POLICY_DEFAULT'] = policy['values'][policy['default']]
    c = '''// SPDX-License-Identifier: MIT
// Generated by portable/generate.py. Edit portable/catalog.json instead.
#ifndef DESKPORT_CATALOG_H
#define DESKPORT_CATALOG_H
'''
    c += '\n'.join(f'#define DP_CATALOG_{k} {v}' for k, v in constants.items()) + '\n'
    c += f'''static const double dp_catalog_tuning_values[] = {{{numbers}}};
static const char *const dp_catalog_tuning_labels[] = {{{labels}}};
static inline int dp_catalog_is_base_port(int port) {{
    if (port < DP_CATALOG_BASE_PORT || port > 65535) return 0;
    const int delta = port - DP_CATALOG_BASE_PORT;
    return delta / DP_CATALOG_PORT_STEP < DP_CATALOG_PORT_COUNT && delta % DP_CATALOG_PORT_STEP == 0;
}}
// Zero denotes an invalid endpoint; never silently route to the default host.
static inline int dp_catalog_control_port(int base) {{
    return dp_catalog_is_base_port(base) ? base + DP_CATALOG_CONTROL_OFFSET : 0;
}}
static inline int dp_catalog_display_policy_valid(int value) {{
    return {' || '.join('value == DP_CATALOG_POLICY_' + k for k in policy['values'])};
}}
#endif
'''
    java = '''// SPDX-License-Identifier: MIT
// Generated by portable/generate.py. Edit portable/catalog.json instead.
package com.deskport.core;

public final class DPCatalog {
    private DPCatalog() {}
'''
    java += '\n'.join(f'    public static final int {k} = {v};' for k, v in constants.items()) + '\n'
    java += f'''    private static final double[] TUNING = {{{numbers}}};
    private static final String[] LABELS = {{{labels}}};
    public static double[] tuningValues() {{ return TUNING.clone(); }}
    public static String[] tuningLabels() {{ return LABELS.clone(); }}
    public static boolean isBasePort(int port) {{
        if (port < BASE_PORT || port > 65535) return false;
        int delta = port - BASE_PORT;
        return delta / PORT_STEP < PORT_COUNT && delta % PORT_STEP == 0;
    }}
    public static int controlPort(int base) {{ return isBasePort(base) ? base + CONTROL_OFFSET : 0; }}
    public static boolean displayPolicyValid(int value) {{
        return {' || '.join('value == POLICY_' + k for k in policy['values'])};
    }}
}}
'''
    result = {ROOT / 'include/deskport/catalog.h': c, ROOT / 'java/com/deskport/core/DPCatalog.java': java}
    result.update(contract_outputs(data))
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, content in outputs().items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f'Stale generated catalog: {path}')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)


if __name__ == '__main__':
    main()
